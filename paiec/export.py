RATED_TEMPLATE = '''"""{description}

Generated by scripts/export_version4.py; inference lives in item_pooling_core.py (which uses
logit_normal_core.py and baseline_core.py), difficulty ratings in llm_rating_core.py, and the
fitted parameters in params.json. Without anthropic_api_key.txt next to this file, or when
the API fails, the predictions are exactly those of version 3.
"""

import json
from pathlib import Path

import item_pooling_core
import llm_rating_core
import logit_normal_core

FOLDER = Path(__file__).resolve().parent
PARAMS = json.loads((FOLDER / "params.json").read_text(encoding="utf-8"))
try:
    RATER = llm_rating_core.Rater(FOLDER, PARAMS["rating_api"])
except Exception:
    RATER = None


def _rated(input, labeled):
    if RATER is None or not RATER.active:
        raise RuntimeError("no ratings")
    # Wait a little for new ratings even at budget 0, where they are not used yet: workers are
    # killed at the end of each checkpoint, and the ratings are then ready for the next one.
    items = llm_rating_core.benchmark_items(input, labeled)
    RATER.request(items, PARAMS["rating_api"]["budget_seconds"])
    return item_pooling_core.predict(input, labeled, PARAMS, RATER.lookup)


def predict(input, labeled=None):
    # Any exception or invalid value would fail the whole hosted run, so fall back to the
    # version 3 prediction, then to Phase 4, then to 0.5.
    labeled = labeled or []
    attempts = (lambda: _rated(input, labeled),
                lambda: item_pooling_core.predict(input, labeled, PARAMS),
                lambda: logit_normal_core.predict(input, labeled, PARAMS))
    for attempt in attempts:
        try:
            value = float(attempt())
            if 0.0 <= value <= 1.0:  # also rejects NaN
                return value
        except Exception:
            pass
    return 0.5  # the model's own guess without metadata or labels
'''

GUESSED_TEMPLATE = '''"""{description}

Generated by scripts/export_version5.py; inference lives in item_pooling_core.py (which uses
logit_normal_core.py and baseline_core.py), difficulty ratings and subject guesses in
llm_rating_core.py (which uses guess_core.py), and the fitted parameters in params.json.
Without anthropic_api_key.txt next to this file the predictions are exactly those of version 3;
a subject without a guess (not asked yet, not answered in time, or the API failed) gets
version 4's prior.
"""

import json
from pathlib import Path

import item_pooling_core
import llm_rating_core
import logit_normal_core

FOLDER = Path(__file__).resolve().parent
PARAMS = json.loads((FOLDER / "params.json").read_text(encoding="utf-8"))
try:
    RATER = llm_rating_core.Rater(FOLDER, PARAMS["rating_api"])
except Exception:
    RATER = None


def _rated(input, labeled):
    if RATER is None or not RATER.active:
        raise RuntimeError("no ratings")
    # Guesses for the subject and its partners on this benchmark come first (they are used from
    # budget 0), then ratings; wait a little for both, as version 4 does for ratings.
    _, item = input
    jobs = [RATER.guess_job(s, item) for s in llm_rating_core.benchmark_subjects(input, labeled)]
    jobs += [RATER.rating_job(i) for i in llm_rating_core.benchmark_items(input, labeled)]
    RATER.request_jobs(jobs, PARAMS["rating_api"]["budget_seconds"])
    return item_pooling_core.predict(input, labeled, PARAMS, RATER.lookup, RATER.lookup_guess)


def predict(input, labeled=None):
    # Any exception or invalid value would fail the whole hosted run, so fall back to the
    # version 3 prediction, then to Phase 4, then to 0.5.
    labeled = labeled or []
    attempts = (lambda: _rated(input, labeled),
                lambda: item_pooling_core.predict(input, labeled, PARAMS),
                lambda: logit_normal_core.predict(input, labeled, PARAMS))
    for attempt in attempts:
        try:
            value = float(attempt())
            if 0.0 <= value <= 1.0:  # also rejects NaN
                return value
        except Exception:
            pass
    return 0.5  # the model's own guess without metadata or labels
'''

# Submission kind -> (model.py template, inference modules copied next to it, extra files).
KINDS = {"baseline": (MODEL_TEMPLATE, (baseline_core,), {}),
         "logit_normal": (LOGIT_NORMAL_TEMPLATE, (baseline_core, logit_normal_core), {}),
         "item_pooling": (ITEM_POOLING_TEMPLATE,
                          (baseline_core, logit_normal_core, item_pooling_core), {}),
         "item_pooling_rated": (RATED_TEMPLATE,  # llm_rating_core imports guess_core since version 5
                                (baseline_core, logit_normal_core, item_pooling_core, llm_rating_core,
                                 guess_core),
                                {"prediction_config.json": '{"concurrency": 4}\n'}),
         "item_pooling_guessed": (GUESSED_TEMPLATE,
                                  (baseline_core, logit_normal_core, item_pooling_core, llm_rating_core,
                                   guess_core),
                                  {"prediction_config.json": '{"concurrency": 4}\n'})}


def submission_kind(params):
    """params' model name; Phase 3 baselines have none. Unknown kinds raise, never guess."""
    kind = params.get("model") or ("baseline" if "prior" in params else None)
    if kind not in KINDS:
        raise ValueError(f"no submission template for model {kind!r}")
    return kind


def write_submission(params, out_dir, description):
    """Create out_dir with model.py, the inference module(s), any extra files and params.json."""
    template, modules, extras = KINDS[submission_kind(params)]
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "model.py").write_text(template.format(description=description),
                                      encoding="utf-8", newline="\n")
    for module in modules:
        shutil.copyfile(module.__file__, out_dir / f"{module.__name__.split('.')[-1]}.py")
    for name, text in extras.items():
        (out_dir / name).write_text(text, encoding="utf-8", newline="\n")
    (out_dir / "params.json").write_text(json.dumps(params, indent=1, sort_keys=True) + "\n",
                                         encoding="utf-8", newline="\n")
    return out_dir
