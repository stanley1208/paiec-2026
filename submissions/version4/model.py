"""Version 4: version 3 (item pooling, scale 0) plus LLM difficulty ratings at trust 0.5, fitted on all public binary benchmarks.

Generated by scripts/export_version4.py; inference lives in item_pooling_core.py (which uses
logit_normal_core.py and baseline_core.py), difficulty ratings in llm_rating_core.py, and the
fitted parameters in params.json. Without anthropic_api_key.txt next to this file, or when
the API fails, the predictions are exactly those of version 3.
"""

import json
from pathlib import Path

import item_pooling_core
import llm_rating_core
import logit_normal_core

FOLDER = Path(__file__).resolve().parent
PARAMS = json.loads((FOLDER / "params.json").read_text(encoding="utf-8"))
try:
    RATER = llm_rating_core.Rater(FOLDER, PARAMS["rating_api"])
except Exception:
    RATER = None


def _rated(input, labeled):
    if RATER is None or not RATER.active:
        raise RuntimeError("no ratings")
    # Wait a little for new ratings even at budget 0, where they are not used yet: workers are
    # killed at the end of each checkpoint, and the ratings are then ready for the next one.
    items = llm_rating_core.benchmark_items(input, labeled)
    RATER.request(items, PARAMS["rating_api"]["budget_seconds"])
    return item_pooling_core.predict(input, labeled, PARAMS, RATER.lookup)


def predict(input, labeled=None):
    # Any exception or invalid value would fail the whole hosted run, so fall back to the
    # version 3 prediction, then to Phase 4, then to 0.5.
    labeled = labeled or []
    attempts = (lambda: _rated(input, labeled),
                lambda: item_pooling_core.predict(input, labeled, PARAMS),
                lambda: logit_normal_core.predict(input, labeled, PARAMS))
    for attempt in attempts:
        try:
            value = float(attempt())
            if 0.0 <= value <= 1.0:  # also rejects NaN
                return value
        except Exception:
            pass
    return 0.5  # the model's own guess without metadata or labels
