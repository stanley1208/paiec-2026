"""Phase 4 model 'logit_normal' (options {"scale": 0.5}), fitted on all public binary benchmarks.

Generated by scripts/export_submission.py; inference lives in logit_normal_core.py (which
uses baseline_core.py) and the fitted parameters in params.json.
"""

import json
from pathlib import Path

import logit_normal_core

PARAMS = json.loads(Path(__file__).with_name("params.json").read_text(encoding="utf-8"))


def predict(input, labeled=None):
    # Any exception or invalid value would fail the whole hosted run.
    try:
        value = float(logit_normal_core.predict(input, labeled or [], PARAMS))
        if 0.0 <= value <= 1.0:  # also rejects NaN
            return value
    except Exception:
        pass
    return 0.5  # the model's own guess without metadata or labels
