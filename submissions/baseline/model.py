"""Phase 3 baseline 'beta_binomial_subject' (options {}), fitted on all public binary benchmarks.

Generated by scripts/export_submission.py; inference lives in baseline_core.py and the
fitted parameters in params.json.
"""

import json
from pathlib import Path

import baseline_core

PARAMS = json.loads(Path(__file__).with_name("params.json").read_text(encoding="utf-8"))


def predict(input, labeled=None):
    # Any exception or invalid value would fail the whole hosted run.
    try:
        value = float(baseline_core.predict(input, labeled or [], PARAMS))
        if 0.0 <= value <= 1.0:  # also rejects NaN
            return value
    except Exception:
        pass
    return PARAMS["global_mean"]
