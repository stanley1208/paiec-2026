"""Phase 4 model with item pooling 'item_pooling' (options {"scale": 0.0}), fitted on all public binary benchmarks.

Generated by scripts/export_submission.py; inference lives in item_pooling_core.py (which
uses logit_normal_core.py and baseline_core.py) and the fitted parameters in params.json.
"""

import json
from pathlib import Path

import item_pooling_core
import logit_normal_core

PARAMS = json.loads(Path(__file__).with_name("params.json").read_text(encoding="utf-8"))


def predict(input, labeled=None):
    # Any exception or invalid value would fail the whole hosted run, so fall back to the
    # Phase 4 prediction, then to 0.5.
    for core in (item_pooling_core, logit_normal_core):
        try:
            value = float(core.predict(input, labeled or [], PARAMS))
            if 0.0 <= value <= 1.0:  # also rejects NaN
                return value
        except Exception:
            pass
    return 0.5  # the model's own guess without metadata or labels
